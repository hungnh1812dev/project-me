import {
  BUILT_IN_TYPE_NAMES,
  COMPONENT_NAME_SEPARATOR,
  FILTER_INPUT_NAMES,
  QUERY_TYPE_NAME,
  SCALAR_NAMES,
  SHARED_TYPE_NAMES,
  TYPE_SUFFIXES,
} from '../../application/Graphql.constants';

/** Two sources generate the same GraphQL name; nothing is renamed to hide it. */
export class GraphqlNameClashError extends Error {
  constructor(
    readonly generatedName: string,
    readonly first: string,
    readonly second: string,
  ) {
    super(
      `GraphQL name "${generatedName}" is generated by both ${first} and ${second}. Rename one of them.`,
    );
    this.name = 'GraphqlNameClashError';
  }
}

const WORD_SEPARATORS = /[-_]+/;

function upperFirst(word: string): string {
  return `${word.charAt(0).toUpperCase()}${word.slice(1)}`;
}

/** `cv-page` -> `CvPage`, `teamSize` -> `TeamSize`, `team_size` -> `TeamSize`. */
export function pascalCase(name: string): string {
  return name.split(WORD_SEPARATORS).filter(Boolean).map(upperFirst).join('');
}

/** `cv-page` -> `cvPage`. */
export function camelCase(name: string): string {
  const pascal = pascalCase(name);
  return `${pascal.charAt(0).toLowerCase()}${pascal.slice(1)}`;
}

/** Names of the types and root fields generated for one content type. */
export function rootNamesOf(slug: string) {
  const type = pascalCase(slug);
  const item = camelCase(slug);
  return {
    type,
    page: `${type}${TYPE_SUFFIXES.PAGE}`,
    filter: `${type}${TYPE_SUFFIXES.FILTER}`,
    sort: `${type}${TYPE_SUFFIXES.SORT}`,
    sortField: `${type}${TYPE_SUFFIXES.SORT_FIELD}`,
    itemField: item,
    listField: `${item}${TYPE_SUFFIXES.LIST_FIELD}`,
  };
}

/** `CvPage` + `experience` -> `CvPage_Experience`; again with `role` -> `CvPage_Experience_Role`. */
export function componentTypeName(parent: string, field: string): string {
  return `${parent}${COMPONENT_NAME_SEPARATOR}${pascalCase(field)}`;
}

/**
 * Claims names for one namespace (types, or the fields of `Query`) and
 * throws when a second source asks for a taken one.
 */
export class NameClaims {
  private readonly owners = new Map<string, string>();

  claim(name: string, source: string): void {
    const owner = this.owners.get(name);
    if (owner !== undefined)
      throw new GraphqlNameClashError(name, owner, source);
    this.owners.set(name, source);
  }
}

/** A type namespace with the shared and built-in type names already taken. */
export function newTypeNameClaims(): NameClaims {
  const claims = new NameClaims();
  const reserved = [
    QUERY_TYPE_NAME,
    ...BUILT_IN_TYPE_NAMES,
    ...Object.values(SCALAR_NAMES),
    ...Object.values(SHARED_TYPE_NAMES),
    ...Object.values(FILTER_INPUT_NAMES),
  ];
  for (const name of reserved) claims.claim(name, `the shared type "${name}"`);
  return claims;
}
