import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import type {
  ContentTypeDefinition,
  FieldDefinition,
} from './definition.schema';
import {
  buildSnapshot,
  emptySnapshot,
  hashDefinition,
  planMigration,
  quoteIdentifier,
  renderMigrationSql,
} from './sql-generator';

const CV_PAGE: ContentTypeDefinition = JSON.parse(
  readFileSync(
    join(__dirname, '..', '..', '..', 'content', 'schemas', 'cv-page.json'),
    'utf8',
  ),
) as ContentTypeDefinition;

function post(fields: FieldDefinition[]): ContentTypeDefinition {
  return { slug: 'post', kind: 'collection', draftAndPublish: true, fields };
}

const TITLE: FieldDefinition = { name: 'title', type: 'string' };
const TAGS: FieldDefinition = {
  name: 'tags',
  type: 'component',
  repeatable: true,
  fields: [
    { name: 'label', type: 'string' },
    {
      name: 'links',
      type: 'component',
      repeatable: true,
      fields: [{ name: 'url', type: 'string' }],
    },
  ],
};

function diff(before: ContentTypeDefinition[], after: ContentTypeDefinition[]) {
  return planMigration(buildSnapshot(before), after);
}

describe('sql-generator', () => {
  describe('initial cv-page migration', () => {
    const plan = planMigration(emptySnapshot(), [CV_PAGE]);
    const sql = renderMigrationSql(plan);

    it('creates the content schema first', () => {
      expect(plan.statements[0]).toBe('CREATE SCHEMA IF NOT EXISTS "content";');
    });

    it('creates exactly the 8 tables of SPEC §8.2', () => {
      const created = plan.statements
        .map((statement) => /^CREATE TABLE "content"\."(\w+)"/.exec(statement))
        .filter((match) => match !== null)
        .map((match) => match[1]);
      expect(created).toEqual([
        'cv_page',
        'cv_page__skill',
        'cv_page__experience',
        'cv_page__experience__role',
        'cv_page__project',
        'cv_page__education',
        'cv_page__language',
        'cv_page__reference',
      ]);
    });

    it('adds the root partial unique indexes and list index', () => {
      expect(sql).toContain(
        'CREATE UNIQUE INDEX "cv_page_draft_uq" ON "content"."cv_page" ("document_id") WHERE "published_at" IS NULL;',
      );
      expect(sql).toContain(
        'CREATE UNIQUE INDEX "cv_page_published_uq" ON "content"."cv_page" ("document_id") WHERE "published_at" IS NOT NULL;',
      );
      expect(sql).toContain(
        'CREATE INDEX "cv_page_published_idx" ON "content"."cv_page" ("published_at", "created_at" DESC);',
      );
    });

    it('links components to their direct parent with ON DELETE CASCADE', () => {
      expect(sql).toContain(
        'CONSTRAINT "cv_page__experience__role_parent_fk" FOREIGN KEY ("parent_id") REFERENCES "content"."cv_page__experience" ("id") ON DELETE CASCADE',
      );
      expect(sql).toContain(
        'CREATE INDEX "cv_page__experience__role_parent_idx" ON "content"."cv_page__experience__role" ("parent_id", "order_index");',
      );
      expect(sql).toContain('"component_uid" uuid NOT NULL');
      expect(sql).toContain('"order_index" integer NOT NULL DEFAULT 0');
    });

    it('maps field types to columns', () => {
      expect(sql).toContain('"is_main" boolean');
      expect(sql).toContain('"team_size" integer');
      expect(sql).toContain('"tech_stack" jsonb');
      expect(sql).toContain('"repository_link" text');
    });

    it('is not destructive and records the slug', () => {
      expect(plan.destructiveChanges).toEqual([]);
      expect(plan.changedSlugs).toEqual(['cv-page']);
      expect(sql.startsWith('-- Generated by content:generate.')).toBe(true);
    });
  });

  it('plans nothing when definitions are unchanged', () => {
    const plan = diff([CV_PAGE], [CV_PAGE]);
    expect(plan).toMatchObject({
      statements: [],
      destructiveChanges: [],
      changedSlugs: [],
    });
  });

  it('adds a column without flagging it destructive', () => {
    const plan = diff(
      [post([TITLE])],
      [post([TITLE, { name: 'publishedOn', type: 'date' }])],
    );
    expect(plan.statements).toEqual([
      'ALTER TABLE "content"."post" ADD COLUMN "published_on" date;',
    ]);
    expect(plan.destructiveChanges).toEqual([]);
  });

  it('flags a dropped field as destructive', () => {
    const plan = diff(
      [post([TITLE, { name: 'body', type: 'richtext' }])],
      [post([TITLE])],
    );
    expect(plan.statements).toEqual([
      'ALTER TABLE "content"."post" DROP COLUMN "body";',
    ]);
    expect(plan.destructiveChanges).toEqual(['Drop column post.body']);
  });

  it('flags a column type change as destructive and casts in place', () => {
    const plan = diff(
      [post([{ name: 'rank', type: 'string' }])],
      [post([{ name: 'rank', type: 'integer' }])],
    );
    expect(plan.statements).toEqual([
      'ALTER TABLE "content"."post" ALTER COLUMN "rank" TYPE integer USING "rank"::integer;',
    ]);
    expect(plan.destructiveChanges).toEqual([
      'Change type of post.rank from text to integer',
    ]);
  });

  it('needs no DDL when the column type stays the same', () => {
    const plan = diff(
      [post([{ name: 'body', type: 'string' }])],
      [post([{ name: 'body', type: 'richtext' }])],
    );
    expect(plan.statements).toEqual([]);
    expect(plan.changedSlugs).toEqual(['post']);
    expect(renderMigrationSql(plan)).toContain('metadata only');
  });

  it('treats metadata changes as changes without DDL', () => {
    const plan = diff(
      [post([TITLE])],
      [{ ...post([TITLE]), draftAndPublish: false }],
    );
    expect(plan.statements).toEqual([]);
    expect(plan.changedSlugs).toEqual(['post']);
  });

  it('creates new component tables parent first', () => {
    const plan = diff([post([TITLE])], [post([TITLE, TAGS])]);
    const tables = plan.statements
      .filter((statement) => statement.startsWith('CREATE TABLE'))
      .map((statement) => statement.split('\n')[0]);
    expect(tables).toEqual([
      'CREATE TABLE "content"."post__tags" (',
      'CREATE TABLE "content"."post__tags__links" (',
    ]);
    expect(plan.statements).not.toContain(
      'CREATE SCHEMA IF NOT EXISTS "content";',
    );
  });

  it('drops removed component tables children first, as destructive', () => {
    const plan = diff([post([TITLE, TAGS])], [post([TITLE])]);
    expect(plan.statements).toEqual([
      'DROP TABLE "content"."post__tags__links";',
      'DROP TABLE "content"."post__tags";',
    ]);
    expect(plan.destructiveChanges).toEqual([
      'Drop table post__tags__links',
      'Drop table post__tags',
    ]);
  });

  it('drops every table of a removed content type', () => {
    const plan = diff([post([TITLE, TAGS]), CV_PAGE], [CV_PAGE]);
    expect(plan.statements).toEqual([
      'DROP TABLE "content"."post__tags__links";',
      'DROP TABLE "content"."post__tags";',
      'DROP TABLE "content"."post";',
    ]);
    expect(plan.changedSlugs).toEqual(['post']);
    expect(plan.nextSnapshot.contentTypes).not.toHaveProperty('post');
  });

  it('hashes definitions independent of key order', () => {
    const reordered = JSON.parse(
      '{"fields":[{"type":"string","name":"title"}],"draftAndPublish":true,"kind":"collection","slug":"post"}',
    ) as ContentTypeDefinition;
    expect(hashDefinition(reordered)).toBe(hashDefinition(post([TITLE])));
    expect(hashDefinition(post([TITLE, TAGS]))).not.toBe(
      hashDefinition(post([TAGS, TITLE])),
    );
  });

  it('quotes identifiers and escapes embedded quotes', () => {
    expect(quoteIdentifier('cv_page')).toBe('"cv_page"');
    expect(quoteIdentifier('a"b')).toBe('"a""b"');
  });
});
