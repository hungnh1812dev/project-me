import baseEslint from '@abyss/base-config/eslint';
import nextPlugin from '@next/eslint-plugin-next';
import reactHooks from 'eslint-plugin-react-hooks';
import globals from 'globals';

const TEST_FILES = ['**/*.test.{ts,tsx}'];

const DEEP_FEATURE_IMPORT_BAN = {
  regex: '^\\.\\./[^./][^/]*/',
  message: 'Import another feature through its index.ts, not a deep path.',
};
const TEST_UTILS_BAN = {
  group: ['**/*.fixture', '**/*.fixture.*'],
  message: 'Test fixtures are for *.test.* files only.',
};
const siblingFeatureBan = (feature) => ({
  regex: `^\\.\\./${feature}$`,
  message: `features/${feature} and this feature may not depend on each other.`,
});

const restrictImports = (files, patterns, ignores = []) => ({
  files,
  ignores,
  rules: { 'no-restricted-imports': ['error', { patterns }] },
});

const NO_RAW_RADIO = {
  selector:
    "JSXOpeningElement[name.name='input'] > JSXAttribute[name.name='type'][value.value='radio']",
  message: 'Use Radio from @abyss/form-commons.',
};
const NO_RAW_TEXTAREA = {
  selector: "JSXOpeningElement[name.name='textarea']",
  message: 'Use Textarea from @abyss/form-commons.',
};

export default [
  ...baseEslint({
    tsconfigRootDir: import.meta.dirname,
    // .next/: Next build output; next-env.d.ts: generated by Next.
    ignores: ['.next/**', 'next-env.d.ts'],
  }),
  reactHooks.configs.flat['recommended-latest'],
  nextPlugin.configs['core-web-vitals'],
  { languageOptions: { globals: globals.browser } },
  // A later config replaces earlier no-restricted-imports options, so each
  // block below repeats the bans that apply to its files.
  restrictImports(
    ['src/**'],
    [TEST_UTILS_BAN],
    [...TEST_FILES, 'src/features/**'],
  ),
  // config is the lowest layer: it may use pure lib helpers, never the API
  // client or a feature.
  restrictImports(
    ['src/config/**'],
    [
      TEST_UTILS_BAN,
      {
        group: ['**/lib/Api.client'],
        message: 'config may not depend on the API client.',
      },
      {
        regex: '^\\.\\./features(/|$)',
        message: 'config may not depend on a feature.',
      },
    ],
    TEST_FILES,
  ),
  restrictImports(
    ['src/config/Security.constants.ts'],
    [
      TEST_UTILS_BAN,
      {
        group: ['./Reviewer.constants'],
        message: 'Third-party origins live in Security.constants itself.',
      },
    ],
    TEST_FILES,
  ),
  restrictImports(
    ['src/features/**'],
    [DEEP_FEATURE_IMPORT_BAN, TEST_UTILS_BAN],
    TEST_FILES,
  ),
  // auth and reviewer both build on session and never on each other.
  restrictImports(
    ['src/features/auth/**'],
    [DEEP_FEATURE_IMPORT_BAN, TEST_UTILS_BAN, siblingFeatureBan('reviewer')],
    TEST_FILES,
  ),
  restrictImports(
    ['src/features/reviewer/**'],
    [DEEP_FEATURE_IMPORT_BAN, TEST_UTILS_BAN, siblingFeatureBan('auth')],
    TEST_FILES,
  ),
  restrictImports(
    ['src/features/session/**'],
    [
      DEEP_FEATURE_IMPORT_BAN,
      TEST_UTILS_BAN,
      siblingFeatureBan('auth'),
      siblingFeatureBan('reviewer'),
    ],
    TEST_FILES,
  ),
  {
    files: ['src/**'],
    rules: {
      'no-restricted-syntax': ['error', NO_RAW_RADIO, NO_RAW_TEXTAREA],
    },
  },
];
